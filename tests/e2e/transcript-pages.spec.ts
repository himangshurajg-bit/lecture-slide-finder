import {test,expect} from '@playwright/test';
test('long transcripts page every match, preserve notes and reset safely on query/replacement',async({page})=>{
 await page.goto('/');
 const segments=Array.from({length:302},(_,i)=>({start:i,end:i+1,text:`Passage ${i+1} force motion`}));
 await page.locator('#transcript-file').setInputFiles({name:'long.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(segments))});
 await expect(page.locator('.cue')).toHaveCount(150);
 await expect(page.locator('#result-summary')).toHaveText('302 passages · showing 1–150');
 await expect(page.locator('#results-prev')).toBeDisabled();
 await page.locator('#results-next').click();
 await expect(page.locator('.cue p').first()).toHaveText('Passage 151 force motion');
 await expect(page.locator('#result-page')).toHaveText('Page 2 of 3');
 await page.locator('#results-next').click();
 await expect(page.locator('.cue')).toHaveCount(2);
 await expect(page.locator('#results-next')).toBeDisabled();
 await page.locator('.save').last().click();
 await expect(page.locator('#notes')).toContainText('Passage 302 force motion');
 await expect(page.locator('#result-page')).toHaveText('Page 3 of 3');
 await page.locator('#results-prev').click();await page.locator('#results-next').click();
 await expect(page.locator('.save').last()).toHaveAttribute('aria-pressed','true');
 await page.locator('#query').fill('302');await expect(page.locator('.cue')).toHaveCount(1);
 await expect(page.locator('#result-pages')).toBeHidden();
 await page.locator('#query').fill('force');
 await expect(page.locator('#result-page')).toHaveText('Page 1 of 3');
 await page.locator('#results-next').click();
 await page.locator('#query').fill('absent');
 await expect(page.locator('.cue')).toHaveCount(0);await expect(page.locator('#result-pages')).toBeHidden();
 await page.locator('#query').fill('');
 page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Try a sample'}).click();
 await expect(page.locator('.cue')).toHaveCount(3);await expect(page.locator('#result-pages')).toBeHidden();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
